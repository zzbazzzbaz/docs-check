_BY_ID: dict[str, str] = dict(RULE_TEXTS)

_SRC_KINDS = ("规范原文：", "规范样张：", "用户确认：")


def text(rule_id: str) -> str:
    """规则内容（含来源前缀，报告用）；编号不存在直接 `KeyError`。"""
    return _BY_ID[rule_id]


def content(rule_id: str) -> str:
    """规则内容的人话（去掉来源前缀，批注用）；未知编号返回空串。"""
    src = _BY_ID.get(rule_id)
    if not src:
        return ""
    for kind in _SRC_KINDS:
        if src.startswith(kind):
            return src[len(kind) :]
    return src
